TICKET_WEIGHTS = {"primary": 10, "alt": 9}


def _norm(s):
    return "".join(str(s or "").split())


def resolve_row(picked, kind):
    """中文行键匹配（去空白归一）；全不命中 → 兜底行。"""
    rows = LAYOUT_ROWS if kind == "layouts" else STYLE_ROWS
    fallback = LAYOUT_FALLBACK if kind == "layouts" else STYLE_FALLBACK
    np_ = _norm(picked)
    for r in rows:
        if np_ and np_ == _norm(r[0]):
            return r
    return next(r for r in rows if r[0] == fallback)


def draw(row, rng):
    """行内加权抽签：主选×10 + 每个备选×9（无行外票），返回抽中中文名。"""
    _, primary, alts = row
    w = TICKET_WEIGHTS
    return rng.choice([primary] * w["primary"] + alts * w["alt"])


def run(layout_row, style_row, seed=None):
    rng = random.Random(seed)  # 版式先抽、风格后抽（共用一 rng，顺序固定）
    return {"layout": draw(resolve_row(layout_row, "layouts"), rng),
            "style": draw(resolve_row(style_row, "styles"), rng)}


def main():
    ap = argparse.ArgumentParser(description="② 行内抽签（程序段，自闭环全中文）")
    ap.add_argument("--layout-row", required=True, help="① 出参 layout_row（中文行键）")
    ap.add_argument("--style-row", required=True, help="① 出参 style_row（中文行键）")
    ap.add_argument("--seed", type=int, default=None, help="抽签种子（缺省真随机）")
    ap.add_argument("--out", default=None, help="写文件路径（缺省打印 stdout）")
    args = ap.parse_args()
    text = json.dumps(run(args.layout_row, args.style_row, args.seed),
                      ensure_ascii=False, indent=1)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"✓ {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
